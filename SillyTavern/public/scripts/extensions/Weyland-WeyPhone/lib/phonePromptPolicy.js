import { isClaudeModel } from '../../quick-reply-ext/src/promptModifiers.js';
import { copycatCourseCorrection } from './copycatInstructions.js';

// WeyPhone's own cut of PromptOS's Gemini Bypass (quick-reply-ext/src/promptModifiers.js). Same
// wording where it still applies, but reframed for requests that have NO analysis step at all: the
// roleplay version tells Gemini to skip "the Weyland Analysis" and end a "pre-analysis", which on
// the phone would point at something that doesn't exist. The CLAUDE/Z.AI/DEEPSEEK "proceed as
// normal" line is dropped - on the phone there is no analysis for them to proceed with.
export const WEYPHONE_GEMINI_BYPASS = `SPECIFIC INSTRUCTIONS:
- If you are based on GEMINI, GoogleAI, or MIMO: We must avoid reasoning as much as possible. Use ONLY up to brief 2 sections in your Google Self_Talk/Initial reasoning, then get out of reasoning immediately. Do NOT perform any analysis - this request has no analysis step. This prevents a fatal recursive reasoning loop. Do not reason about skipping, this alone will trigger recursion - simply skip and begin your response. Your goal is brevity and speed in reasoning. Do not loop, move to the response as quickly as possible.`;

const COACH_GLOBAL_MACRO = /\{\{\s*getglobalvar\s*::\s*Coach\s*\}\}/gi;

// Current Prompt bakes its six-section analysis directly into rav.teg (Beta assembles its
// analysis in quick-reply-ext's XXX() instead, so Beta's raw teg never carries one).
const ANALYSIS_PROCEDURE_BLOCK = /\[WEYLAND RESPONSE ANALYSIS PROCEDURE[^\]\n]*\][\s\S]*?\[END WEYLAND RESPONSE ANALYSIS PROCEDURE\][ \t]*\r?\n*/g;
// Beta's procedure is now a "scene sheet" (2026-09-28): Anthropic refuses requests whose prompt
// frames that step as a reasoning/analysis procedure ("reverse engineering or duplicating model
// outputs"), and the same content framed as a worksheet goes through. Same job, new markers.
const SCENE_SHEET_BLOCK = /\[WEYLAND SCENE SHEET[^\]\n]*\][\s\S]*?\[END WEYLAND SCENE SHEET\][ \t]*\r?\n*/g;
// Current and Beta's post-history note points back at that analysis ("the six-section analysis
// runs first...") - with the procedure gone it would tell the model to run an analysis it has
// no instructions for. XXX() drops this same note for Beta when its Analysis toggle is off.
const ANALYSIS_CLIENT_NOTE = /¦Weyland Tavern client note:[^¦]*¦[ \t]*\r?\n*/g;
// Old Prompt 2026 carries a 14-step <think> reasoning procedure in its post-history instead.
// Everything from its header through the "Give me your best." sign-off is that procedure; the
// macro lines after it (ThoughtSet, POV, focus, clothing, language) are kept.
const OLD_REASONING_PROCEDURE = /\[FINAL ROLEPLAY DIRECTIVES\][\s\S]*?Give me your best\.[^\n]*\r?\n?/g;

/**
 * The PromptOS course correction for a WeyPhone-owned request, or '' when the player hasn't opted
 * this request type in ("Allow course corrections" in WeyPhone Settings, or Kressa's own switch).
 * Until 2026-10-09 the opt-in only passed Hard Mode (the Coach global); every other Roleplay Shift,
 * dose and Custom Preset was silently dropped. Now it's the same text Copycat sends, built by the
 * shared assembler in its no-scene-sheet form. Linked conversations are generated by the main
 * roleplay and never pass through here.
 */
export function phoneCourseCorrection(context, beta, allowed) {
    if (!allowed) return '';
    const text = copycatCourseCorrection(context, beta, { sheetless: true });
    return text ? `[COURSE CORRECTION]\n${text}\nApply this correction to what you write for this request, and keep the format this request asks for.` : '';
}

/**
 * Puts the course correction where the prompt's old {{getglobalvar::Coach}} slot was (the top of
 * the social-app system prompt), and always removes that slot: Coach is Hard Mode's legacy text,
 * which the correction above already covers in its current wording.
 */
export function applyPhoneCourseCorrection(content, correction = '') {
    const prompt = String(content ?? '');
    let placed = false;
    const replaced = prompt.replace(COACH_GLOBAL_MACRO, () => {
        if (placed || !correction) return '';
        placed = true;
        return correction;
    });
    return correction && !placed ? `${correction}\n\n${replaced}` : replaced;
}

/**
 * WeyPhone-owned requests (unlinked texting, phone app content) never run the roleplay analysis
 * procedure, whichever master prompt is selected and whatever the Analysis toggle says: a text
 * reply is a few short lines, and an analysis block ahead of it is pure cost (and, on models that
 * follow it, leaks <analysis> text into the bubble). Course corrections are the one exception:
 * they're added separately, by phoneCourseCorrection, when the player opts in.
 * Linked conversations are generated by the main roleplay and never pass through here.
 */
/**
 * Prepends WEYPHONE_GEMINI_BYPASS to every WeyPhone-owned request, always (not gated on the
 * PromptOS toggle, which governs the main roleplay). WeyPhone defaults to gemini-3.8-flash, a
 * thinking model; the bypass keeps its reasoning to a couple of brief sections and tells it there
 * is no analysis step. It addresses Gemini/Google/MiMo by name, so other models can ignore it.
 * Applied at the shared send helpers (sendMessage / sendMemoryRequest) so no app can miss it.
 * Idempotent, and never mutates the caller's array.
 *
 * EXCEPT for Claude models (`model` passed and isClaudeModel): Claude's classifier rejects
 * requests that tell the model how to handle its reasoning, which is exactly what this text does,
 * so a phone app pointed at Sonnet would just get refused. Same rule the main roleplay applies at
 * send time (quick-reply-ext OnRequestReady). A blank `model` means "the profile decides", which
 * we can't see from here, so the text is kept (the safe default for the Gemini-first phone).
 * @param {Array<{role: string, content: string}>} messages
 * @param {string} [model] the model this request is going to, when the caller knows it
 */
export function withGeminiBypass(messages, model = '') {
    const list = Array.isArray(messages) ? messages.map(message => ({ ...message })) : [];
    if (isClaudeModel(model)) {
        for (const message of list) {
            if (typeof message.content !== 'string' || !message.content.includes(WEYPHONE_GEMINI_BYPASS)) continue;
            message.content = message.content.replace(`${WEYPHONE_GEMINI_BYPASS}\n\n`, '').replace(WEYPHONE_GEMINI_BYPASS, '');
        }
        return list.filter(message => !(message.role === 'system' && message.content === ''));
    }
    if (list.some(message => String(message.content ?? '').includes(WEYPHONE_GEMINI_BYPASS))) return list;
    const first = list[0];
    if (first?.role === 'system') {
        first.content = `${WEYPHONE_GEMINI_BYPASS}\n\n${first.content ?? ''}`;
        return list;
    }
    return [{ role: 'system', content: WEYPHONE_GEMINI_BYPASS }, ...list];
}

export function stripAnalysisProcedure(content) {
    return String(content ?? '')
        .replace(ANALYSIS_PROCEDURE_BLOCK, '')
        .replace(SCENE_SHEET_BLOCK, '')
        .replace(ANALYSIS_CLIENT_NOTE, '')
        .replace(OLD_REASONING_PROCEDURE, '');
}

